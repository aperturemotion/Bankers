// Writes src/pe/spxlogo.ts — SpaceX's wordmark as inline SVG path data, read from public/brand/spacex.svg (simple-icons, copied from the
// installed package; the official mark, never redrawn — the brief's rule 7). A separate module: parts.tsx/brandsvg.ts are canonical kit files.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = fs.readFileSync(path.join(root, "public", "brand", "spacex.svg"), "utf8");
const vb = src.match(/viewBox="([^"]+)"/)?.[1];
const d = [...src.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
if (!vb || !d.length) throw new Error("spacex.svg: no viewBox or no path — refusing");
const [, , W, H] = vb.split(/\s+/).map(Number);
// the mark's own ink extent (simple-icons centres a wide mark in a 24-unit square): measured from the path's numbers
const nums = d.join(" ").match(/-?\d*\.?\d+/g).map(Number);
fs.writeFileSync(path.join(root, "src", "pe", "spxlogo.ts"),
  `// ★ GENERATED by scratchpad/mkspxlogo.mjs from public/brand/spacex.svg (simple-icons) — do not edit.\n` +
  `export const SPX_VB = ${JSON.stringify(vb)};\nexport const SPX_W = ${W}, SPX_H = ${H};\nexport const SPX_D = ${JSON.stringify(d)};\n`);
console.log("spxlogo.ts:", vb, d.length, "path(s),", nums.length, "numbers");
