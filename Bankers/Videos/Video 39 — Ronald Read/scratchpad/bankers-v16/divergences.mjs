// VIDEO 15 — THE GUARD'S LIST, ARMED BEFORE THE TAKE (root CLAUDE.md: takes have repeatedly been recorded from the BRIEF,
// not the corrected script). Every line script.mjs corrected gets:
//   · pattern   — matches the brief's line as a MICROPHONE says it AND as whisper writes it (digits, "N dollars"),
//                 and must NOT match the corrected line;
//   · spoken    — the brief's line as spoken (the take's spelling: whisper's digits);
//   · corrected — the line VO_SCRIPT.txt gives the voice.
// Written in JS and serialised with JSON.stringify, so no pattern ever passes through a hand-edited JSON string (the
// "\b is a backspace in JSON" trap). Run: node scratchpad/divergences.mjs → src/pe/divergences.json
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { CHANGES } from "./script.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
// (Video 16: five lines corrected, armed before the take)
const PATTERNS = {
  pensions: { pattern: "money from pensions", spoken: "A fund raises money from pensions, buys companies, improves them, then sells." },
  payouts: { pattern: "(twenty twenty-two|2022) to (twenty twenty-five|2025)", spoken: "From 2022 to 2025, yearly payouts stayed under 15% of what the funds hold." },
  listings: { pattern: "listed since (twenty twenty-two|2022)", spoken: "About 70 have listed since 2022, against over 400 from 2017 to 2021." },
  exits: { pattern: "american firms sold", spoken: "From July to September, American firms sold 165 billion dollars of companies, 51% more than from April to June." },
  fundraising: { pattern: "but,? fundraising", spoken: "But fundraising is on pace for its first year under 300 billion dollars since 2020." },
};
const list = CHANGES.map((c) => {
  const p = PATTERNS[c.id];
  if (!p) throw new Error(`no pattern for ${c.id}`);
  return { id: c.id, severity: c.severity, accepted: false, pattern: p.pattern, spoken: p.spoken, brief: c.brief, corrected: c.corrected, verified: c.why };
});
const stale = Object.keys(PATTERNS).filter((id) => !CHANGES.some((c) => c.id === id));
if (stale.length) throw new Error(`patterns with no change in script.mjs: ${stale.join(", ")}`);
fs.writeFileSync(path.join(here, "..", "src", "pe", "divergences.json"),
  JSON.stringify({ _doc: "Generated by scratchpad/divergences.mjs. The render guard (scratchpad/guard.mjs) blocks the MP4 while the wired take says any of these brief lines, unless an entry is accepted.", divergences: list }, null, 1) + "\n");
console.log(`${list.length} divergences armed`);
