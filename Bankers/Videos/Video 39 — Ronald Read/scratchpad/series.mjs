// Builds src/bnx/series.ts — the S&P 500 line every chart in Video 37 plots (never hand-drawn).
//   node scratchpad/series.mjs
//
// ONE DATASET (the brief): index levels = multpl's S&P 500 MONTHLY AVERAGE CLOSES (scratchpad/data/sp500_monthly_multpl.json,
// 682 months, Jan 1970 – Oct 2026, read off multpl's own table and checked against its yearly sums). Two documented insertions:
//   1. each crash's DAILY peak and trough close (historyofmarket.com's dates and levels — the brief's crash-size source) is
//      inserted as a vertex at its exact date, so the drawn line reaches the levels the −48% / −34% / −49% / −57% are measured
//      between (a monthly average misses a one-day top: Jan 1973 averaged 118.40, the peak close was 120.24);
//   2. the last point is the OFFICIAL close of Fri 9 Oct 2026, 7,811.54 (FRED SP500; AP) — multpl's newest row (7,874.39) is its
//      "current price" field, which matches no official close (fact-check, 2026-10-12).
// Monthly averages are placed mid-month (t = year + (month − 0.5) / 12); daily points at their exact dates.
import fs from "fs";

const J = JSON.parse(fs.readFileSync("scratchpad/data/sp500_monthly_multpl.json", "utf8"));
const rows = J.monthly;
if (rows.length !== 682) throw new Error(`expected 682 months, got ${rows.length}`);
const tOf = (ym) => { const [y, m] = ym.split("-").map(Number); return y + (m - 0.5) / 12; };
const dayT = (y, m, d) => y + (m - 1) / 12 + (d - 1) / 365.25;

// the monthly line, minus multpl's Oct-2026 "current price" row
const pts = rows.filter(([ym]) => ym !== "2026-10").map(([ym, v]) => ({ t: tOf(ym), v, k: "m" }));
if (rows[rows.length - 1][0] !== "2026-10") throw new Error("newest row is not 2026-10 — re-check the source before dropping it");

// ★ the four crashes (historyofmarket.com: peak close → trough close, price only)
const CRASHES = [
  { id: "c73", peak: { d: [1973, 1, 11], v: 120.24 }, trough: { d: [1974, 10, 3], v: 62.28 }, pct: 48.2, show: "−48%" },
  { id: "c87", peak: { d: [1987, 8, 25], v: 336.77 }, trough: { d: [1987, 12, 4], v: 223.92 }, pct: 33.5, show: "−34%" },
  { id: "c00", peak: { d: [2000, 3, 24], v: 1527.46 }, trough: { d: [2002, 10, 9], v: 776.76 }, pct: 49.1, show: "−49%" },
  { id: "c07", peak: { d: [2007, 10, 9], v: 1565.15 }, trough: { d: [2009, 3, 9], v: 676.53 }, pct: 56.8, show: "−57%" },
];
for (const c of CRASHES) {
  const real = (1 - c.trough.v / c.peak.v) * 100;
  if (Math.abs(real - c.pct) > 0.06) throw new Error(`${c.id}: levels give −${real.toFixed(2)}%, source says −${c.pct}%`);
  pts.push({ t: dayT(...c.peak.d), v: c.peak.v, k: "peak" }, { t: dayT(...c.trough.d), v: c.trough.v, k: "trough" });
}
// the end: the official close
const NOW = { d: [2026, 10, 9], v: 7811.54 };
pts.push({ t: dayT(...NOW.d), v: NOW.v, k: "now" });
pts.sort((a, b) => a.t - b.t);

// ★ Bob's four buys (Carlson 2014): end-1972, Aug 1987, end-Dec 1999, Oct 2007 — placed on the line at those dates
const BUYS = [
  { id: "b72", t: dayT(1972, 12, 29), amt: 6000, show: "$6,000", date: "DEC 1972", crash: "c73" },
  { id: "b87", t: dayT(1987, 8, 25), amt: 46000, show: "$46,000", date: "AUG 1987", crash: "c87" },
  { id: "b99", t: dayT(1999, 12, 31), amt: 68000, show: "$68,000", date: "DEC 1999", crash: "c00" },
  { id: "b07", t: dayT(2007, 10, 9), amt: 64000, show: "$64,000", date: "OCT 2007", crash: "c07" },
];
if (BUYS.reduce((a, b) => a + b.amt, 0) !== 184000) throw new Error("Bob's buys must total $184,000");

// ★ the new high after each crash: the first MONTHLY AVERAGE above the monthly average of the peak's month (one dataset)
const monthly = pts.filter((p) => p.k === "m");
const mAt = (t) => monthly.reduce((best, p) => (Math.abs(p.t - t) < Math.abs(best.t - t) ? p : best));
const NEW_HIGHS = CRASHES.map((c) => {
  const pk = mAt(dayT(...c.peak.d));
  const after = monthly.find((p) => p.t > dayT(...c.trough.d) && p.v > pk.v);
  if (!after) throw new Error(`${c.id}: no new high after the trough`);
  const y = Math.floor(after.t), m = Math.round((after.t - y) * 12 + 0.5);
  return { id: c.id, t: after.t, v: after.v, ym: `${y}-${String(m).padStart(2, "0")}` };
});

const r2 = (x) => Math.round(x * 1e4) / 1e4;
const out = `// AUTO-GENERATED by scratchpad/series.mjs — DO NOT EDIT. Source and insertions: see that file's header.
export type SP = [number, number];
/** the S&P 500: multpl monthly averages (mid-month), the four crashes' daily peak/trough closes, the 9 Oct 2026 close */
export const SP500: SP[] = ${JSON.stringify(pts.map((p) => [r2(p.t), p.v]))};
export const CRASHES = ${JSON.stringify(CRASHES.map((c) => ({ id: c.id, peakT: r2(dayT(...c.peak.d)), peakV: c.peak.v, troughT: r2(dayT(...c.trough.d)), troughV: c.trough.v, pct: c.pct, show: c.show })))} as const;
export const BUYS = ${JSON.stringify(BUYS.map((b) => ({ ...b, t: r2(b.t) })))} as const;
export const NEW_HIGHS = ${JSON.stringify(NEW_HIGHS.map((h) => ({ ...h, t: r2(h.t) })))} as const;
export const NOW = { t: ${r2(dayT(...NOW.d))}, v: ${NOW.v}, show: "7,812", date: "OCT 2026" } as const;
export const START = { t: ${r2(tOf("1972-01"))}, v: 103.3, show: "103", date: "JAN 1972" } as const;
export const RECORD = { t: ${r2(dayT(2026, 10, 6))}, v: 7818.93, date: "6 OCT 2026" } as const;
`;
fs.writeFileSync("src/bnx/series.ts", out);
console.log(`${pts.length} points (${monthly.length} monthly + 8 crash closes + the 9 Oct close)`);
for (const h of NEW_HIGHS) console.log(`new high after ${h.id}: ${h.ym} (${h.v})`);
