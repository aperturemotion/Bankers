// Writes src/tsla/brandsvg.ts — each company logo's VECTOR content, read from the file in public/brand/ (the one source).
//   node scratchpad/mkbrand.mjs
// ★ WHY (Timur, 2026-09-26: "the jpmorgan text is jittering a little bit"): Logo drew the marks as a CSS MASK (knockout) or
// an <img>. Both are rasterised as bitmaps and SNAPPED to the pixel grid, so under the camera's slow sub-pixel drift the
// thin serif JPMorganChase wordmark jumped 0.5–2 px at irregular frames (measured in lossless stills with
// scratchpad/jitter.py, while the layout itself moved a smooth 0.2–0.3 px/frame). Inline SVG paths are painted at the
// exact sub-pixel position every frame. The generator strips editor metadata, comments and titles, and keeps each
// file's own viewBox; it refuses if a file yields no drawable elements.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const FILES = { micron: "micron.svg", jpm: "jpmorganchase.svg", skhynix: "skhynix.svg", samsung: "samsung_wordmark.svg" };

const out = {};
for (const [brand, file] of Object.entries(FILES)) {
  const src = fs.readFileSync(path.join(root, "public", "brand", file), "utf8");
  const open = src.match(/<svg\b[^>]*>/);
  if (!open) throw new Error(`${file}: no <svg> element`);
  const vb = open[0].match(/viewBox="([^"]+)"/);
  if (!vb) throw new Error(`${file}: no viewBox`);
  let inner = src.slice(open.index + open[0].length, src.lastIndexOf("</svg>"));
  inner = inner
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/<metadata\b[\s\S]*?<\/metadata>/g, "")
    .replace(/<sodipodi:namedview\b[\s\S]*?(\/>|<\/sodipodi:namedview>)/g, "")
    .replace(/<title\b[\s\S]*?<\/title>/g, "")
    .replace(/\s(inkscape|sodipodi):[a-zA-Z-]+="[^"]*"/g, "")
    .replace(/\s+/g, " ")
    .trim();
  const drawable = (inner.match(/<(path|polygon|rect|circle|ellipse|polyline)\b/g) ?? []).length;
  if (!drawable) throw new Error(`${file}: nothing drawable after stripping — refusing`);
  out[brand] = { viewBox: vb[1], inner, drawable };
}
const ts = `// ★ GENERATED by scratchpad/mkbrand.mjs from public/brand/*.svg — do not edit (re-run the script if a file changes).
// Each logo's own vector content, so parts.tsx Logo paints real paths at sub-pixel positions (no bitmap snapping).
export const BRAND_SVG: Record<"micron" | "jpm" | "skhynix" | "samsung", { viewBox: string; inner: string }> = ${JSON.stringify(
  Object.fromEntries(Object.entries(out).map(([k, v]) => [k, { viewBox: v.viewBox, inner: v.inner }])), null, 1)};
`;
fs.writeFileSync(path.join(root, "src", "tsla", "brandsvg.ts"), ts);
console.log(Object.entries(out).map(([k, v]) => `${k}: viewBox ${v.viewBox}, ${v.drawable} drawable, ${v.inner.length} chars`).join("\n"));
